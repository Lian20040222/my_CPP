#include <iostream>
using namespace std;


/* 标识符命名规则 
    1、标识符由字母、数字、下划线组成，且不能以数字开头
    2、标识符不能是C++的关键字
    3、标识符区分大小写
    4、标识符命名要有意义，便于理解
*/
int main() 
{
    int abc = 10; // 定义一个整数变量abc并赋值为10
    int _abc = 20; // 定义一个整数变量_abc并赋值为20
    int abc_123 = 30; // 定义一个整数变量abc_123并赋值为30
    // int 123abc = 40; // 错误，标识符不能以数字开头
    // int int = 50; // 错误，int是C++的关键字，不能作为变量名使用

    return 0;
}

#include <iostream>
using namespace std;

int main() 
{
    // 比较运算符 == != > < >= <=
    int a = 10;
    int b = 3;
    cout << "a == b = " << (a == b) << endl; // 输出a == b = 0
    cout << "a != b = " << (a != b) << endl; // 输出a != b = 1
    cout << "a > b = " << (a > b) << endl; // 输出a > b = 1
    cout << "a < b = " << (a < b) << endl; // 输出a < b = 0
    cout << "a >= b = " << (a >= b) << endl; // 输出a >= b = 1
    cout << "a <= b = " << (a <= b) << endl; // 输出a <= b = 0
    
}

#include <iostream>
using namespace std;

int main() 
{
    // 常用转义字符
    // \n 换行符
    cout << "Hello, World!\nHello, World!" << endl; // 输出两行Hello, World!
    // \t 制表符
    cout << "Hello, \tWorld!" << endl; // 输出Hello,     World!

    // 输出"\\""

    cout << "\\" << endl; // 输出一个"\"

    return 0;
}

 
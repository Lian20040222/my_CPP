#include <iostream>
using namespace std;

// 指针

int main() 
{
    // 指针是一个变量，它的值为另一个变量的地址
    // 定义一个指针变量
    int a = 10;
    int * p;
    //指针P记录a的地址
    p = &a;
    cout << "a的地址为：" << &a << endl;
    cout << "p的值为：" << p << endl;

    // 可以使用解引用的方式来访问指针指向的变量的值(指针前加*号)
    *p = 100;
    cout << a << endl;
    cout << *p << endl;

    //指针所占用的内存空间大小      在32位系统中，指针占用4个字节，在64位系统中，指针占用8个字节
    cout << "sizeof(p) = " << sizeof(p) << endl;


    //空指针和野指针
    int * p1 = NULL; //空指针
    //野指针是指向一块已经释放的内存空间的指针
    // int * p2 = (int *)0x00123140; //野指针

    //1、常量指针是指向一个常量的指针，不能通过指针来修改常量的值(指针本身的值可以改变，但不能通过指针来修改指针所指向的值)
    const int * p3 = &a;
    // *p3 = 100; //错误
    cout << *p3 << endl;

    //2、指针常量是指针本身的值不能改变，但可以通过指针来修改指针所指向的值
    int * const p4 = &a;
    // p4 = &b; //错误
    cout << *p4 << endl;
    //3、常量指针常量是指针本身的值不能改变，也不能可以通过指针来修改指针所指向的值
    const int * const p5 = &a;
    // *p5 = 100; //错误
    // p5 = &b; //错误
    cout << *p5 << endl;
}

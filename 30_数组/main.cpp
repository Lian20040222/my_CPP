#include <iostream>
using namespace std;

int main() 
{
    // 数组
    // 数组的特点:
    // 1. 数组的元素必须是相同类型的
    // 2. 数组的元素必须是连续存储的
    // 3. 数组的元素可以是任意类型的
    // 数组的定义：
    // 数组名[数组大小];
    // 数组的初始化：
    // 数组名[数组大小] = {元素1, 元素2, ... 元素n};
    // 数组的遍历：
    // for (int i = 0; i < 数组大小; i ++)
    // {
    //     cout << 数组名[i] << endl;
    // }

    int a[5] = {1, 2, 3, 4, 5};
    for (int i = 0; i < 5; i ++)
    {
        cout << a[i] << endl;
    }

    //数组名的用途
    // 1. 获取数组的首地址
    cout << "数组的首地址为：" << a << endl;
    // 2. 获取数组的元素个数
    cout << "数组的大小为：" << sizeof(a)<< endl;
    cout << "数组的元素大小为：" << sizeof(a[0])<< endl;
}
 
